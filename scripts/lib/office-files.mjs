export function buildXlsx(sheets) {
  const sheetEntries = sheets.map((sheet, i) => [`xl/worksheets/sheet${i + 1}.xml`, sheetXml(sheet)]);
  return zip([
    [
      "[Content_Types].xml",
      `${xmlHead}<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>${sheets.map((_, i) => `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`).join("")}<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/></Types>`,
    ],
    [
      "_rels/.rels",
      `${xmlHead}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>`,
    ],
    [
      "xl/workbook.xml",
      `${xmlHead}<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>${sheets.map((s, i) => `<sheet name="${esc(s.name)}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`).join("")}</sheets></workbook>`,
    ],
    [
      "xl/_rels/workbook.xml.rels",
      `${xmlHead}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${sheets.map((_, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`).join("")}<Relationship Id="rId${sheets.length + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>`,
    ],
    ["xl/styles.xml", stylesXml],
    ...sheetEntries,
  ]);
}

/* ------------------------------ DOCX ------------------------------ */

const run = (text, { bold, italic, size, color } = {}) =>
  `<w:r><w:rPr>${bold ? "<w:b/>" : ""}${italic ? "<w:i/>" : ""}${color ? `<w:color w:val="${color}"/>` : ""}${size ? `<w:sz w:val="${size}"/>` : ""}</w:rPr><w:t xml:space="preserve">${esc(text)}</w:t></w:r>`;
const para = (text, { style, bold, italic, after } = {}) =>
  `<w:p><w:pPr>${style ? `<w:pStyle w:val="${style}"/>` : ""}${after !== undefined ? `<w:spacing w:after="${after}"/>` : ""}</w:pPr>${text === "" ? "" : run(text, { bold, italic })}</w:p>`;

function table(rows, widths, { header = true, rowHeight } = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const grid = widths.map((w) => `<w:gridCol w:w="${w}"/>`).join("");
  const body = rows
    .map((row, r) => {
      const isHead = header && r === 0;
      return `<w:tr><w:trPr><w:cantSplit/>${rowHeight && !isHead ? `<w:trHeight w:val="${rowHeight}" w:hRule="atLeast"/>` : ""}${isHead ? "<w:tblHeader/>" : ""}</w:trPr>${row
        .map(
          (cell, c) =>
            `<w:tc><w:tcPr><w:tcW w:w="${widths[c]}" w:type="dxa"/>${isHead ? '<w:shd w:val="clear" w:color="auto" w:fill="DCE8E2"/>' : ""}</w:tcPr><w:p><w:pPr><w:spacing w:before="40" w:after="40"/></w:pPr>${cell === "" ? "" : run(cell, { bold: isHead || (!header && c === 0) })}</w:p></w:tc>`,
        )
        .join("")}</w:tr>`;
    })
    .join("");
  return `<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:w="${total}" w:type="dxa"/><w:tblLayout w:type="fixed"/></w:tblPr><w:tblGrid>${grid}</w:tblGrid>${body}</w:tbl>${para("", { after: 120 })}`;
}

export const docx = { h1: (t) => para(t, { style: "Title" }), h2: (t) => para(t, { style: "Heading1" }), p: (t, o) => para(t, o), note: (t) => para(t, { italic: true }), table };

