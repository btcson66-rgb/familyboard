// Dependency-free generators for the downloadable Office files (.xlsx and .docx).
// Both formats are ZIP packages of XML parts, so a tiny ZIP writer is all that is needed.
// Output is deterministic (fixed timestamps, stable ordering) so `build-downloads --check`
// can confirm the committed files match what the script produces.
import { deflateRawSync } from "node:zlib";

const crcTable = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buffer) {
  let c = 0xffffffff;
  for (const byte of buffer) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

// Fixed DOS date/time: 2026-11-20 00:00:00
const dosTime = 0;
const dosDate = ((2026 - 1980) << 9) | (11 << 5) | 20;

export function zip(entries) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const [name, content] of entries) {
    const nameBuf = Buffer.from(name, "utf8");
    const data = Buffer.from(content, "utf8");
    const packed = deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(8, 8);
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(packed.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    locals.push(local, nameBuf, packed);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8);
    central.writeUInt16LE(8, 10);
    central.writeUInt16LE(dosTime, 12);
    central.writeUInt16LE(dosDate, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(packed.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt32LE(offset, 42);
    centrals.push(central, nameBuf);
    offset += local.length + nameBuf.length + packed.length;
  }
  const centralBuf = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, centralBuf, end]);
}

const esc = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
const xmlHead = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n';

/* ------------------------------ XLSX ------------------------------ */

function colName(index) {
  let name = "";
  for (let n = index + 1; n > 0; n = Math.floor((n - 1) / 26)) name = String.fromCharCode(65 + ((n - 1) % 26)) + name;
  return name;
}

// style ids: 0 normal, 1 header, 2 currency, 3 wrapped text, 4 bold, 5 note (italic)
function sheetXml({ rows, widths, currencyCols = [], freeze = true, header = true, blankRows = 0, extraXml = "" }) {
  const totalRows = rows.length + blankRows;
  const cols = widths
    .map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"${currencyCols.includes(i) ? ' style="2"' : ""}/>`)
    .join("");
  const rowXml = rows
    .map((row, r) => {
      const cells = row
        .map((cell, c) => {
          if (cell === "" || cell === null || cell === undefined) return "";
          const ref = `${colName(c)}${r + 1}`;
          const style = r === 0 && header ? 1 : 3;
          if (typeof cell === "object" && cell.formula)
            return `<c r="${ref}" s="${cell.style ?? 2}"><f>${esc(cell.formula)}</f><v>0</v></c>`;
          if (typeof cell === "object" && cell.style !== undefined)
            return `<c r="${ref}" s="${cell.style}" t="inlineStr"><is><t xml:space="preserve">${esc(cell.text)}</t></is></c>`;
          if (typeof cell === "number") return `<c r="${ref}" s="${currencyCols.includes(c) ? 2 : 0}"><v>${cell}</v></c>`;
          return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(cell)}</t></is></c>`;
        })
        .join("");
      return `<row r="${r + 1}"${r === 0 ? ' ht="32" customHeight="1"' : ""}>${cells}</row>`;
    })
    .join("");
  const pane = freeze
    ? '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
    : '<sheetViews><sheetView workbookViewId="0"/></sheetViews>';
  const lastCol = colName(Math.max(...rows.map((r) => r.length), widths.length) - 1);
  return `${xmlHead}<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><dimension ref="A1:${lastCol}${totalRows}"/>${pane}<sheetFormatPr defaultRowHeight="18"/><cols>${cols}</cols><sheetData>${rowXml}</sheetData>${extraXml}<pageMargins left="0.5" right="0.5" top="0.6" bottom="0.6" header="0.3" footer="0.3"/><pageSetup orientation="landscape" fitToHeight="0"/></worksheet>`;
}

